const dbPath = process.env.DATABASE_PATH ?? "./data/serate.db";
const db = new Database(dbPath);
db.pragma("journal_mode = WAL");

const stmt = db.prepare("UPDATE movies SET runtime = ? WHERE title = ? AND runtime IS NULL");
let updated = 0;
let missing = 0;
for (const [title, minutes] of Object.entries(RUNTIMES)) {
  const r = stmt.run(minutes, title);
  if (r.changes > 0) updated += r.changes;
  else {
    const exists = db.prepare("SELECT 1 FROM movies WHERE title = ?").get(title);
    if (!exists) {
      missing += 1;
      console.warn(`Non in catalogo: ${title}`);
    }
  }
}
console.log(`Durate aggiornate: ${updated} film (${missing} titoli non trovati).`);
